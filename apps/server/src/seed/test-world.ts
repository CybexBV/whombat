/** Local Amsterdam (CEST) wall-clock time on the seed day, as ISO: `at('11:22')`. */
export function at(hhmm: string, dayOffset = 0): string {
  const [h, m] = hhmm.split(':').map(Number) as [number, number];
  return new Date(Date.UTC(2026, 8, 23 + dayOffset, h - 2, m)).toISOString();
}

