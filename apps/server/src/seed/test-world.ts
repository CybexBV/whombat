/**
 * Dusty's keys: what a new Whombat's agent holds (`AGENT_DEFAULT_KEYS`, as `createTheAgent` gives them; one-agent.md
 * OA-S04) outside the six risk rows, where the mock world's own choices stay (merges blocked, deploys asked), and the
 * mock world's tier wherever it names a key (OA-S26, OA-S87).
 */
export const DUSTY_KEYS: GrantInput[] = (() => {
  const keys = new Map<string, GrantInput>();
  for (const g of grantsFromKeySet('', AGENT_DEFAULT_KEYS))
    if (keyTierRowOf(g.keyId) === null) keys.set(g.keyId, { keyId: g.keyId, tier: g.tier });
  for (const g of MOCK_KEYS) keys.set(g.keyId, g);
  return [...keys.values()];
})();

