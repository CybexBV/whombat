/**
 * Writes `src/faceData.ts`: each face's bust drawing and its poses, taken from the design handoff's expressions
 * (`docs/design-handoff/whombat-crew/expressions/svg`). Every expression is the bust's drawing with a few parts changed
 * (the head's tilt, the ears, the eyes, brows, mouth, glasses, a blush and a small symbol), so a pose keeps only what
 * differs. `face.test.ts` builds the data again and checks that it matches, and that every pose put back on the bust
 * gives its expression file exactly.
 *
 *   pnpm --filter @whombat/avatars face-data
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildFaceData } from '../src/faceBuild';

const here = import.meta.dirname;
const root = join(here, '../../..');
const data = buildFaceData(
  (stem) => readFileSync(join(here, '../svg', `${stem}.svg`), 'utf8'),
  (stem, expression) =>
    readFileSync(
      join(root, 'docs/design-handoff/whombat-crew/expressions/svg', `${stem}-${expression}.svg`),
      'utf8',
    ),
);
const out = `/**
 * Generated by \`scripts/face-data.ts\` from the bust drawings in \`svg/\` and the design handoff's expressions: do not
 * edit. Each face's bust and its poses (only the parts a pose changes); \`face.ts\` puts them together.
 */
import type { FaceDrawings } from './faceBuild';

export const FACE_DRAWINGS: FaceDrawings = ${JSON.stringify(data, null, 2)};
`;
writeFileSync(join(here, '../src/faceData.ts'), out);
console.log('wrote src/faceData.ts');
