const CATALOGS = { en: EN, nl: NL } as const;

export function clientTranslator(locale?: string | null): Translator<typeof EN> {
  return createTranslator(CATALOGS, typeof locale === 'string' ? locale : undefined);
}

export function tClient<K extends ClientMessageKey>(
  locale: string | null | undefined,
  key: K,
  vars?: MessageVars,
): string {
  return clientTranslator(locale).t(key, vars);
}

export function tpClient<K extends ClientMessageKey>(
  locale: string | null | undefined,
  key: K,
  count: number,
  vars?: MessageVars,
): string {
  return clientTranslator(locale).tp(key, count, vars);
}
