/**
 * Renders `tokens.css` (CSS custom properties) from the TS tokens. Pure: the file is written by
 * `scripts/generate-css.ts` and a test fails when the committed file is stale.
 *
 * Theme colors keep the reference names (`--bg`, `--sf2`, `--btnfg`, …) so inline styles from the
 * mocks port 1:1. Light is on `:root` and `[data-theme="light"]`, dark on `[data-theme="dark"]`.
 */
import {
  chartColors,
  codeColors,
  councilRoomColors,
  fixedColors,
  humanTones,
  statusColors,
  statusTextColors,
  type ThemeColors,
  themeColors,
} from './colors.js';
import { FACES, facePalettes } from './faces.js';
import {
  breakpoints,
  chartShadows,
  contentWidths,
  durations,
  layout,
  radii,
  shadows,
  spacing,
  zIndex,
} from './scale.js';
import type { ThemeName } from './themes.js';
import { emojiFontFamily, fontFamilies, type TypeStyle, typeScale } from './typography.js';

export const kebab = (name: string): string =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([a-zA-Z])([0-9])/g, '$1-$2')
    .toLowerCase();

/** Numbers as CSS wants them (`0.05`, `-0.02`, `15.5`). */
const num = (n: number): string => String(n);

/** Normalizes a reference literal to Biome's CSS output: `rgba(0,0,0,.4)` → `rgba(0, 0, 0, 0.4)`. */
export const cssColor = (value: string): string =>
  value.replace(/([,(\s])\.(\d)/g, '$10.$2').replace(/,(?=\S)/g, ', ');

/** Font shorthand for a type style, e.g. `700 44px / 1.02 var(--font-sans)`. */
export function typeShorthand(style: TypeStyle): string {
  const size =
    style.lineHeight === undefined
      ? `${num(style.size)}px`
      : `${num(style.size)}px / ${num(style.lineHeight)}`;
  return `${style.weight} ${size} var(--font-${style.family})`;
}

type Decl = readonly [name: string, value: string];

export function staticDeclarations(): Decl[] {
  const decls: Decl[] = [];
  const push = (name: string, value: string) => decls.push([`--${name}`, value]);

  push('font-sans', fontFamilies.sans.replaceAll("'", '"'));
  push('font-mono', fontFamilies.mono.replaceAll("'", '"'));
  push('font-emoji', emojiFontFamily.replaceAll("'", '"'));
  for (const [name, style] of Object.entries(typeScale) as [string, TypeStyle][]) {
    push(`type-${kebab(name)}`, typeShorthand(style));
    push(
      `type-${kebab(name)}-tracking`,
      style.tracking === undefined ? 'normal' : `${num(style.tracking)}em`,
    );
  }

  for (const [name, px] of Object.entries(radii)) push(`radius-${kebab(name)}`, `${px}px`);
  for (const px of spacing) push(`space-${px}`, `${px}px`);
  for (const [name, value] of Object.entries({ ...shadows, ...chartShadows }))
    push(`shadow-${kebab(name)}`, cssColor(value));
  for (const [name, px] of Object.entries(contentWidths)) push(`max-${kebab(name)}`, `${px}px`);
  for (const [name, px] of Object.entries(layout)) push(`size-${kebab(name)}`, `${px}px`);
  for (const [name, px] of Object.entries(breakpoints)) push(`bp-${kebab(name)}`, `${px}px`);
  for (const [name, ms] of Object.entries(durations)) push(`duration-${kebab(name)}`, `${ms}ms`);
  for (const [name, z] of Object.entries(zIndex)) push(`z-${kebab(name)}`, String(z));

  for (const [name, value] of Object.entries(codeColors)) push(`code-${kebab(name)}`, cssColor(value));
  for (const [name, value] of Object.entries(statusColors)) push(`status-${name}`, value);
  for (const [name, value] of Object.entries(fixedColors)) push(kebab(name), cssColor(value));
  humanTones.forEach((value, i) => {
    push(`tone-${i + 1}`, value);
  });
  for (const face of FACES) {
    push(`face-${face}`, facePalettes[face].accent);
    push(`face-${face}-deep`, facePalettes[face].deep);
  }
  return decls;
}

/** `warnText` → `warn-text`; digits stay attached (`sf2`, `line2`), as in the reference. */
export const themeColorCssName = (name: string): string =>
  name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

export function themeDeclarations(theme: ThemeName): Decl[] {
  const colors: ThemeColors = themeColors[theme];
  return [
    ...(Object.entries({ ...colors, ...statusTextColors[theme] }) as [string, string][]).map(
      ([name, value]): Decl => [`--${themeColorCssName(name)}`, cssColor(value)],
    ),
    ...(Object.entries(chartColors[theme]) as [string, string][]).map(
      ([name, value]): Decl => [`--${name}`, cssColor(value)],
    ),
    ...(Object.entries(councilRoomColors[theme]) as [string, string][]).map(
      ([name, value]): Decl => [`--${themeColorCssName(name)}`, cssColor(value)],
    ),
  ];
}

const block = (selector: string, lines: readonly string[]): string =>
  `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`;
const declLines = (decls: readonly Decl[]): string[] => decls.map(([n, v]) => `${n}: ${v};`);

export function renderTokensCss(): string {
  return [
    '/* Generated by packages/tokens/scripts/generate-css.ts from src/*.ts. Do not edit by hand. */\n',
    block(':root', declLines(staticDeclarations())),
    block(':root,\n[data-theme="light"]', ['color-scheme: light;', ...declLines(themeDeclarations('light'))]),
    block('[data-theme="dark"]', ['color-scheme: dark;', ...declLines(themeDeclarations('dark'))]),
  ].join('\n');
}
