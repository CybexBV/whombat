/**
 * Text files generated from the logo geometry (written by `scripts/export-icons.ts`; tests fail when a
 * committed copy is stale). Pure: no I/O.
 */
import { renderLogoSvg, SYMBOL_HEIGHT, SYMBOL_MASK, SYMBOL_SMALL_PATH, SYMBOL_WIDTH } from './index.js';
import { BRAND_MARK_DEFINITIONS, type BrandMarkName, buildBrandMark } from './marks.js';

/**
 * `assets/marks/<name>.svg` (Whombat marks.md MK-03): a mark as a file of its own, 24 px, its owner's name as the title,
 * so the library is kept and looked at outside the code (`scripts/export-marks.ts`; `assets/marks/SOURCES.md` says where
 * each comes from). `currentColor` draws black in a file.
 */
export function brandMarkSvg(name: BrandMarkName): string {
  const title = BRAND_MARK_DEFINITIONS[name].name.replaceAll('&', '&amp;').replaceAll('<', '&lt;');
  return `${renderLogoSvg(buildBrandMark(name, 24)).replace(/^<svg([^>]*)>/, `<svg$1 role="img"><title>${title}</title>`)}\n`;
}

/**
 * `favicon.svg`: the small symbol, burrow ink, switching to paper when the browser prefers dark (what the
 * package README describes; its own favicon.svg lost the style rule).
 */
export function faviconSvg(colors: { ink: string; paper: string }): string {
  // The package's favicon box and placement: the face on a 120 × 120 canvas, 9 units down.
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120">
<title>Whombat</title>
<style>path{fill:${colors.ink}}@media (prefers-color-scheme:dark){path{fill:${colors.paper}}}</style>
<path transform="translate(0 9)" d="${SYMBOL_SMALL_PATH}"/>
</svg>
`;
}

/**
 * Android vector drawable for the status bar: the small symbol, white on transparent, 22 dp wide inside the
 * 24 dp icon (1 dp padding), vertically centred. Groups apply scale, then translate.
 */
export function androidSmallIconXml(): string {
  const scale = 22 / SYMBOL_WIDTH;
  const round = (n: number) => Math.round(n * 1000) / 1000;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Status-bar icon: the small Whombat symbol, white on transparent. Generated by
     packages/brand/scripts/export-icons.ts from @whombat/brand; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
  <group
      android:scaleX="${round(scale)}"
      android:scaleY="${round(scale)}"
      android:translateX="1"
      android:translateY="${round((24 - SYMBOL_HEIGHT * round(scale)) / 2)}">
    <group android:translateX="-3" android:translateY="-8">
      <path
          android:fillColor="#FFFFFFFF"
          android:pathData="${SYMBOL_SMALL_PATH}" />
    </group>
  </group>
</vector>
`;
}

/** `manifest.webmanifest` for the web app (installable; icons are the Ink tile, full-bleed). */
export function webManifest(colors: { background: string }): string {
  const icons = [192, 512].flatMap((size) =>
    ['any', 'maskable'].map((purpose) => ({
      src: `/icon-${size}.png`,
      sizes: `${size}x${size}`,
      type: 'image/png',
      purpose,
    })),
  );
  const manifest = {
    name: 'Whombat',
    short_name: 'Whombat',
    start_url: '/',
    display: 'standalone',
    background_color: colors.background,
    theme_color: colors.background,
    icons,
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/** How wide the face is on Android's 108 dp launcher icon canvas, in dp. */
export const LAUNCHER_FACE_DP = 38;

const argb = (hex: string) => `#FF${hex.replace('#', '').toUpperCase()}`;
const round3 = (n: number) => Math.round(n * 1000) / 1000;
const circlePath = (cx: number, cy: number, r: number) =>
  `M${cx - r} ${cy} a${r} ${r} 0 1 0 ${2 * r} 0 a${r} ${r} 0 1 0 ${-2 * r} 0Z`;

/** The face centred on the 108 dp canvas, `LAUNCHER_FACE_DP` wide, around `body`. */
function launcherVector(comment: string, body: string): string {
  const scale = round3(LAUNCHER_FACE_DP / SYMBOL_WIDTH);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${comment} Generated by
     packages/brand/scripts/export-icons.ts from @whombat/brand; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
  <group
      android:scaleX="${scale}"
      android:scaleY="${scale}"
      android:translateX="${round3((108 - SYMBOL_WIDTH * scale) / 2)}"
      android:translateY="${round3((108 - SYMBOL_HEIGHT * scale) / 2)}">
    <group android:translateX="-3" android:translateY="-8">
${body}
    </group>
  </group>
</vector>
`;
}

/**
 * The Android launcher icon's foreground (adaptive icon): the full symbol, its mask painted in order on the Ink
 * background — what it keeps in paper, what it cuts in ink. A vector, like the status-bar icon: a launcher draws it
 * fresh, where Samsung kept showing an earlier bitmap of the same name after an update.
 */
export function androidLauncherForegroundXml(colors: { ink: string; paper: string }): string {
  const body = SYMBOL_MASK.map((s) => {
    const color = argb(s.keep ? colors.paper : colors.ink);
    if (s.kind === 'stroke')
      return `      <path
          android:strokeColor="${color}"
          android:strokeWidth="${s.width}"
          android:strokeLineCap="round"
          android:strokeLineJoin="round"
          android:pathData="${s.d}" />`;
    const d = s.kind === 'circle' ? circlePath(s.cx, s.cy, s.r) : s.d;
    return `      <path
          android:fillColor="${color}"
          android:pathData="${d}" />`;
  }).join('\n');
  return launcherVector('Launcher icon foreground: the Whombat face in paper, its features in ink.', body);
}

/** Its Android 13 themed-icon layer: the small symbol (one path with the features as holes), white. */
export function androidLauncherMonochromeXml(): string {
  return launcherVector(
    'Launcher icon, themed: the small Whombat symbol, white.',
    `      <path
          android:fillColor="#FFFFFFFF"
          android:pathData="${SYMBOL_SMALL_PATH}" />`,
  );
}
